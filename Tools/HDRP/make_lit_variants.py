"""Generate KÁRMÁN surface shaders for HDRP from HDRP's own Lit.shader.

Each generated shader keeps every HDRP pass (GBuffer, forward, shadows, depth, motion vectors) and lighting model, but
replaces LitData.hlsl's GetSurfaceAndBuiltinData with a KÁRMÁN surface function (triplanar PBR, launch-site ground,
lunar regolith ...). Usage: python3 make_lit_variants.py <path-to-HDRP-package> Assets/Karman/Shaders  (overwrites Karman<Name>.shader)
"""
import re, sys, os, glob

pkg, out = sys.argv[1], sys.argv[2]
src = open(os.path.join(pkg, "Runtime/Material/Lit/Lit.shader")).read()

# Drop the ray-tracing SubShader (second SubShader block) to keep compile times sane.
first = src.index("    SubShader")
second = src.find("    SubShader", first + 10)
if second > 0:
    end = src.index("    FallBack", second)
    src = src[:second] + src[end:]
src = re.sub(r'\n\s*CustomEditor "[^"]+"', "", src)

VARIANTS = {
    "Triplanar": '''
        _BaseMap ("Albedo", 2D) = "white" {}
        _BumpMap ("Normal", 2D) = "bump" {}
        _ArmMap ("AO/Rough/Metal", 2D) = "white" {}
        _Tiling ("Metres per texture repeat", Float) = 4
        _NormalStrength ("Normal strength", Range(0, 2)) = 1
        _Roughness ("Roughness scale", Range(0,2)) = 1
        _Desaturate ("Desaturate albedo", Range(0,1)) = 0
        _AlbedoStrength ("Albedo texture strength", Range(0,1)) = 1
        _ObjectSpace ("Projection space (0 world, 1 object, 2 site)", Float) = 0
        _Grime ("Weathering amount", Range(0,1)) = 0
        _GrimeScale ("Weathering scale (m)", Float) = 6
        _GrimeColor ("Weathering colour", Color) = (0.32, 0.3, 0.27, 1)
        _Panel ("Slab / panel size (m, 0 = off)", Float) = 0
        _Cull ("Cull", Float) = 2
''',
    "Ground": '''
        _DayTex ("Global day", 2D) = "white" {}
        _NightTex ("Night", 2D) = "black" {}
        _SpecTex ("Ocean mask", 2D) = "black" {}
        _GrassDiff ("Grass albedo", 2D) = "white" {}
        _GrassNor ("Grass normal", 2D) = "bump" {}
        _GrassArm ("Grass ARM", 2D) = "white" {}
        _MacroDiff ("Aerial macro albedo", 2D) = "white" {}
        _SandDiff ("Sand albedo", 2D) = "white" {}
        _SandNor ("Sand normal", 2D) = "bump" {}
        _NightIntensity ("City lights", Float) = 2.5
        _SunDir ("Sun direction (world)", Vector) = (0,1,0,0)
        _SkyColor ("Sky colour (unused in HDRP)", Color) = (0.32, 0.5, 0.78, 1)
''',
    "MoonTerrain": '''
        _ColorTex ("LROC colour", 2D) = "gray" {}
        _NearDiff ("Regolith near albedo", 2D) = "gray" {}
        _NearNor ("Regolith near normal", 2D) = "bump" {}
        _MidDiff ("Regolith mid albedo", 2D) = "gray" {}
        _MidNor ("Regolith mid normal", 2D) = "bump" {}
        _SunIntensity ("Sun intensity (unused in HDRP)", Float) = 4
        _Albedo ("Albedo", Float) = 0.75
        _EarthShine ("Earthshine (unused in HDRP)", Float) = 0.02
        _SunDir ("Sun direction (world)", Vector) = (1,0,0,0)
        _EarthDir ("Earth direction (world)", Vector) = (0,0,1,0)
''',
}

for name, props in VARIANTS.items():
    s = src.replace('Shader "HDRP/Lit"', f'Shader "Karman/{name}"', 1)
    s = s.replace("    Properties\n    {\n", "    Properties\n    {\n" + props, 1)
    s = s.replace('#include "Packages/com.unity.render-pipelines.high-definition/Runtime/Material/Lit/LitData.hlsl"',
                  f'#include "HD/KarmanHD{name}Data.hlsl"')
    open(os.path.join(out, f"Karman{name}.shader"), "w").write(
        f"// GENERATED by Tools/HDRP/make_lit_variants.py from HDRP Lit.shader. Edit KarmanHD{name}Data.hlsl instead.\n" + s)
    print("wrote", name)
